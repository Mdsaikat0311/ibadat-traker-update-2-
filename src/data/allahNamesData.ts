const PINNED_ALLAH_NAMES_KEY = 'ibadat_pinned_allah_names';

export function getPinnedAllahNameIds(): number[] {
  try {
    const raw = localStorage.getItem(PINNED_ALLAH_NAMES_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed.filter((x): x is number => typeof x === 'number') : [];
  } catch {
    return [];
  }
}

export function savePinnedAllahNameIds(ids: number[]): void {
  try {
    localStorage.setItem(PINNED_ALLAH_NAMES_KEY, JSON.stringify(ids));
  } catch (err) {
    console.error('Failed to save pinned names:', err);
  }
}

export function isAllahNamePinned(id: number): boolean {
  return getPinnedAllahNameIds().includes(id);
}

export function togglePinAllahNameId(id: number): { isPinned: boolean; updatedIds: number[] } {
  const current = getPinnedAllahNameIds();
  const exists = current.includes(id);
  let updatedIds: number[];
  if (exists) {
    updatedIds = current.filter(x => x !== id);
  } else {
    // Put newly pinned item at the start of pinned list
    updatedIds = [id, ...current.filter(x => x !== id)];
  }
  savePinnedAllahNameIds(updatedIds);
  return { isPinned: !exists, updatedIds };
}

